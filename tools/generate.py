"""Build r6/tweaks/zzWeightlessClothing/weightless_clothing.yaml from the game's own TweakDB.

Read-only on the game. Uses a TweakDB reader (tweakdb.py, from the author's Iconic Arsenal project; not in this repo), which reads
r6/cache/tweakdb_ep1.bin and names records with WolvenKit's tweakdbstr list.

What it does:
  1. finds every Clothing record (gamedataClothing_Record);
  2. collects the stat modifiers in their statModifiers lists whose statType is BaseStats.Weight;
  3. writes a TweakXL YAML that sets every Additive one with a non-zero value to 0
     (the few vanilla Multiplier ones are already 0: the game uses them to make some quest outfits weightless);
  4. checks the result: every clothing record must end at weight 0, and no record other than clothing may use any
     of the edited modifiers (otherwise the edit would leak into other items).

Run:  python -I tools/generate.py        (from the Weightless-Clothing folder)
"""
import collections
import os
import sys

# the TweakDB reader (tweakdb.py) lives in the author's Iconic Arsenal project, not in this repo:
# set TWEAKDB_READER to the folder that holds it
sys.path.insert(0, os.environ.get("TWEAKDB_READER", r"D:\Code\Cyberpunk2077-Modding\Iconic-Arsenal\tools\gamefiles"))
import tweakdb as T  # noqa: E402

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "r6", "tweaks", "zzWeightlessClothing", "weightless_clothing.yaml")
WEIGHT = "BaseStats.Weight"


def main():
    ctx = T.Ctx()
    db, names = ctx.db, ctx.names
    nm = names.fmt
    clothing = sorted(nm(rid) for rid, t in db.records.items() if db.rtype_names.get(t) == "gamedataClothing_Record")

    def weight_mods(rec):
        out = []
        for mid in db.value(rec + ".statModifiers") or []:
            m = nm(mid)
            st = db.value(m + ".statType")
            if st and nm(st) == WEIGHT:
                out.append((m, db.value(m + ".modifierType"), db.value(m + ".value")))
        return out

    users = collections.Counter()
    info = {}
    for rec in clothing:
        for m, mt, v in weight_mods(rec):
            users[m] += 1
            info[m] = (mt, v)
    edit = sorted(m for m, (mt, v) in info.items() if mt == "Additive" and abs(v) > 1e-6)

    # check 1: after the edit every clothing record weighs 0 (Additive values summed, then multiplied)
    left = []
    for rec in clothing:
        add, mult = 0.0, 1.0
        for m, mt, v in weight_mods(rec):
            if mt == "Additive":
                add += 0.0 if m in edit else v
            elif mt == "Multiplier":
                mult *= v
            else:
                left.append((rec, m, mt))
        if abs(add * mult) > 1e-6:
            left.append((rec, round(add * mult, 3)))
    assert not left, "clothing still weighing something: %s" % left[:10]

    # check 2: the edited modifiers are used only by clothing records
    idx = db.build_ref_index()
    leaks = [(m, nm(k)) for m in edit for k in idx.get(T.tdbid(m), [])
             if db.record_type(nm(k).rpartition(".")[0]) != "gamedataClothing_Record"]
    assert not leaks, "an edited modifier is also used outside clothing: %s" % leaks[:10]

    lines = [
        "# Weightless Clothing: every clothing item weighs 0.",
        "# Generated by tools/generate.py from the game's TweakDB (tweakdb_ep1.bin); don't edit by hand, rerun it.",
        "#",
        "# Clothing weight is a BaseStats.Weight stat modifier in each clothing record's statModifiers list. The game",
        "# shares %d of them across all %d clothing records (one for each base, e.g. OuterChestClothingBase +0.5," % (len(edit), len(clothing)),
        "# and one for each garment type, e.g. Jacket +2.5). Setting those shared values to 0 makes every vanilla",
        "# clothing item weigh 0. The edited modifiers are used by clothing records only (checked when this file was",
        "# generated). Clothing added by other mods weighs 0 only if it reuses these vanilla modifiers.",
        "",
    ]
    for m in edit:
        mt, v = info[m]
        lines.append("%s:  # was +%s, used by %d clothing records" % (m, round(v, 2), users[m]))
        lines.append("  value: 0.0")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("clothing records %d | with a weight %d | modifiers edited %d | already 0 (vanilla multipliers) %d -> %s" % (
        len(clothing), sum(1 for r in clothing if weight_mods(r)), len(edit), len(info) - len(edit), OUT))


if __name__ == "__main__":
    main()
